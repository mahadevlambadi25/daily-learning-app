// Generates prisma/postgres/schema.prisma from prisma/schema.prisma (the single source of truth).
// Local dev and tests use SQLite; production (Vercel + Neon) uses this PostgreSQL copy, which has
// its own migrations folder next to it (prisma/postgres/migrations).
//   node scripts/pg-schema.mjs           write the file
//   node scripts/pg-schema.mjs --check   exit 1 if it is out of date (used by the Vercel build)
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";

const SRC = "prisma/schema.prisma";
const OUT = "prisma/postgres/schema.prisma";

const src = readFileSync(SRC, "utf8");
const datasource = /datasource db \{[^}]*\}/;
if (!datasource.test(src)) throw new Error("datasource block not found in prisma/schema.prisma");

const out =
  "// GENERATED by scripts/pg-schema.mjs from prisma/schema.prisma. Do not edit by hand.\n" +
  src.replace(
    datasource,
    `datasource db {
  provider  = "postgresql"
  url       = env("DATABASE_URL")
  // Neon/Supabase pooled URLs can't run migrations; the build passes the direct URL here.
  directUrl = env("DIRECT_URL")
}`,
  );

if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== out) {
    console.error(`${OUT} is out of date. Run: node scripts/pg-schema.mjs, then create a Postgres migration (see README).`);
    process.exit(1);
  }
  console.log(`✓ ${OUT} is up to date`);
} else {
  mkdirSync("prisma/postgres", { recursive: true });
  writeFileSync(OUT, out);
  console.log(`✓ wrote ${OUT}`);
}
